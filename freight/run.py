"""Run the whole pipeline: simulate, warehouse, checks, analysis, optimisation, figures, dashboard.

    python -m freight.run                 # writes data/, results/, figures/ and docs/index.html
    python -m freight.run --out /tmp/x    # write somewhere else
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from . import analytics as an
from . import optimize as op
from . import plots
from .dashboard import build_dashboard
from .simulate import Assumptions, simulate, write_csv
from .warehouse import assert_quality, build_warehouse, read_table


def _md(df: pd.DataFrame, cols: list[tuple[str, str, str]]) -> str:
    head = "| " + " | ".join(c[1] for c in cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    body = "".join("| " + " | ".join(r[k] if isinstance(r[k], str) else format(r[k], f) for k, _, f in cols) + " |\n" for r in df.to_dict("records"))
    return head + body


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=Path("."), help="repository root to write data/, results/, figures/ and docs/ into")
    ap.add_argument("--seed", type=int, default=Assumptions.seed)
    args = ap.parse_args(argv)
    data_dir, res_dir, fig_dir = args.out / "data", args.out / "results", args.out / "figures"
    res_dir.mkdir(parents=True, exist_ok=True)

    # 1) Simulate the raw feeds and load them into the warehouse
    a = Assumptions(seed=args.seed)
    tables = simulate(a)
    write_csv(tables, data_dir / "raw")
    db_path = data_dir / "freight.db"
    db_path.unlink(missing_ok=True)
    conn = build_warehouse(tables, a, db_path)

    # 2) Data-quality checks: the pipeline stops if any fail
    checks = assert_quality(conn)
    pd.DataFrame({"check": list(checks), "violations": list(checks.values())}).to_csv(res_dir / "data_quality_checks.csv", index=False)

    # 3) Analysis
    d = an.load_delivered(conn)
    carrier_lane, monthly, customers = (read_table(conn, t) for t in ("mart_carrier_lane", "mart_monthly", "mart_customer"))
    scorecard = an.carrier_scorecard(d)
    found = an.findings(d, carrier_lane, customers)
    lane_names = d.drop_duplicates("lane_id").set_index("lane_id").lane_name.str.replace(" > ", " → ").to_dict()
    scorecard.to_csv(res_dir / "carrier_scorecard.csv", index=False, float_format="%.5f")
    carrier_lane.to_csv(res_dir / "carrier_lane.csv", index=False, float_format="%.5f")
    monthly.to_csv(res_dir / "monthly.csv", index=False, float_format="%.5f")
    customers.to_csv(res_dir / "customers.csv", index=False, float_format="%.5f")
    an.lane_cost_breakdown(d).to_csv(res_dir / "lane_cost_breakdown.csv", index=False, float_format="%.5f")

    # 4) Optimisation
    options = op.segment_options(d)
    allocation = op.optimize_allocation(options)
    frontier = op.price_of_reliability(options)
    allocation.table.to_csv(res_dir / "recommended_allocation.csv", index=False, float_format="%.5f")
    frontier.to_csv(res_dir / "price_of_reliability.csv", index=False, float_format="%.5f")
    found["optimization"] = allocation.summary
    (res_dir / "findings.json").write_text(json.dumps(found, indent=2, default=float))

    # 5) Figures and dashboard
    plots.carrier_scorecard(scorecard, fig_dir)
    plots.freight_vs_net(carrier_lane, lane_names, scorecard.set_index("carrier_id").carrier_name.to_dict(), fig_dir)
    plots.monthly_performance(monthly, fig_dir)
    plots.price_of_reliability(frontier, fig_dir)
    plots.margin_overview(an.margin_by(d, "lane_name"), {"Largest customer": found["top_customer_margin_pct"], "All other customers": found["other_customers_margin_pct"]}, fig_dir)
    build_dashboard(d, allocation, frontier, args.out / "docs" / "index.html")

    # 6) Human-readable report
    k, s, o = found["kpis"], found["seasonality"], allocation.summary
    md = (
        "# Results (generated by `python -m freight.run`)\n\n"
        f"Simulated data, seed {args.seed}: {k['shipments']:,} delivered shipments, {k['volume_tonnes']:,.0f} tonnes.\n\n"
        f"* On-time rate {k['on_time_rate']:.1%}; freight cost EUR {k['freight_per_kg']:.3f} per kg; margin after landed cost {k['margin_pct']:.1%}.\n"
        f"* Customs-hold months (Dec, Jan, Jul): {s['late_share_hold_months']:.1%} of shipments late versus {s['late_share_other_months']:.1%} in other months (z = {s['z']:.2f}, p = {s['p_value']:.4f}).\n"
        f"* Cheapest carrier by freight price differs from the cheapest in total on {found['lanes_where_cheapest_changes']} of {found['lanes_total']} lanes.\n"
        f"* Optimised carrier mix: expected cost {o['baseline_cost_per_kg']:.4f} to {o['optimized_cost_per_kg']:.4f} EUR per kg ({o['saving_pct']:.1%}, about EUR {o['saving_eur']:,.0f} over the period) "
        f"while on-time delivery goes from {o['baseline_on_time']:.1%} to {o['optimized_on_time']:.1%}.\n\n"
        "## Carrier scorecard\n\n"
        + _md(scorecard, [("carrier_name", "Carrier", ""), ("shipments", "Shipments", ",d"), ("volume_share", "Volume share", ".1%"), ("on_time_rate", "On time", ".1%"), ("p90_days_late", "P90 days late", ".0f"), ("quote_error_days", "Quote error (days)", "+.2f"), ("freight_per_kg", "Freight EUR/kg", ".3f"), ("net_cost_per_kg", "Net EUR/kg", ".3f"), ("margin_pct", "Margin", ".1%")])
        + "\n## Data-quality checks (violations)\n\n"
        + _md(pd.DataFrame({"check": list(checks), "violations": list(checks.values())}), [("check", "Check", ""), ("violations", "Violations", "d")])
    )
    (res_dir / "RESULTS.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
